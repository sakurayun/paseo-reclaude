import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(__dirname, "..");
const repoRoot = path.resolve(appRoot, "../..");
const entry = path.join(appRoot, "src/terminal/webview/terminal-emulator-webview-entry.ts");
const output = path.join(appRoot, "src/terminal/webview/terminal-emulator-webview-html.ts");

async function resolveTsPath(basePath) {
  const candidates = [
    basePath,
    `${basePath}.ts`,
    `${basePath}.tsx`,
    `${basePath}.js`,
    `${basePath}.jsx`,
    path.join(basePath, "index.ts"),
    path.join(basePath, "index.tsx"),
    path.join(basePath, "index.js"),
    path.join(basePath, "index.jsx"),
  ];
  for (const candidate of candidates) {
    try {
      const stat = await fs.stat(candidate);
      if (stat.isFile()) return candidate;
    } catch {
      // try next candidate
    }
  }
  return basePath;
}

const aliasPlugin = {
  name: "paseo-alias",
  setup(build) {
    build.onResolve({ filter: /^@\// }, async (args) => ({
      path: await resolveTsPath(path.join(appRoot, "src", args.path.slice(2))),
    }));
    build.onResolve({ filter: /^@server\// }, async (args) => ({
      path: await resolveTsPath(
        path.join(repoRoot, "packages/server/src", args.path.slice("@server/".length)),
      ),
    }));
  },
};

// @xterm/addon-ligatures pulls in lru-cache, which imports `node:diagnostics_channel`
// (and calls `channel()`/`tracingChannel()` at module load). This bundle targets the
// browser, where that Node built-in doesn't exist, so esbuild can't resolve it.
// Diagnostics are a no-op in the WebView, so stub the module with inert channels
// instead of failing the build.
export function createNodeBuiltinStubPlugin() {
  return {
    name: "paseo-node-builtin-stub",
    setup(build) {
      build.onResolve({ filter: /^node:diagnostics_channel$/ }, (args) => ({
        path: args.path,
        namespace: "paseo-node-stub",
      }));
      build.onLoad({ filter: /.*/, namespace: "paseo-node-stub" }, () => ({
        contents: `
        const noopChannel = {
          publish() {},
          subscribe() {},
          unsubscribe() {},
          get hasSubscribers() {
            return false;
          },
        };
        export function channel() {
          return noopChannel;
        }
        export function tracingChannel() {
          return {
            start: noopChannel,
            end: noopChannel,
            asyncStart: noopChannel,
            asyncEnd: noopChannel,
            error: noopChannel,
            get hasSubscribers() {
              return false;
            },
            traceSync(fn, thisArg, ...args) {
              return fn.apply(thisArg, args);
            },
            tracePromise(fn, thisArg, ...args) {
              return fn.apply(thisArg, args);
            },
            traceCallback(fn, _position, thisArg, ...args) {
              return fn.apply(thisArg, args);
            },
          };
        }
        export function subscribe() {}
        export function unsubscribe() {}
        export default { channel, tracingChannel, subscribe, unsubscribe };
      `,
        loader: "js",
      }));
    },
  };
}

export async function buildTerminalWebViewHtml() {
  const result = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: ["ios15", "chrome100"],
    loader: {
      ".css": "text",
    },
    plugins: [aliasPlugin, createNodeBuiltinStubPlugin()],
    logLevel: "info",
  });

  const js = result.outputFiles[0]?.text;
  if (!js) {
    throw new Error("terminal webview bundle produced no JavaScript");
  }

  const html = `<!doctype html>
<html>
  <head>
    <meta charset="utf-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no, viewport-fit=cover"
    />
  </head>
  <body>
    <script>${js}</script>
  </body>
</html>`;

  const contents = `// Generated by packages/app/scripts/build-terminal-webview-html.mjs.
// Do not edit by hand.

export const terminalEmulatorWebViewHtml = ${JSON.stringify(html)};
`;

  await fs.writeFile(output, contents);
  console.log(`Wrote ${path.relative(repoRoot, output)} (${html.length} bytes)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await buildTerminalWebViewHtml();
}
